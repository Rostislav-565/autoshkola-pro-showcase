import assert from 'node:assert/strict';
import { once } from 'node:events';
import { existsSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const modulePath = process.env.PLAYWRIGHT_PATH;
const { chromium } = modulePath
  ? await import(pathToFileURL(join(modulePath, 'index.mjs')).href)
  : await import('playwright');
const chrome = process.env.CHROME_PATH || [
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].find(existsSync);
assert.ok(chrome, 'Укажите путь к установленному Chrome или Edge в CHROME_PATH.');

const folder = mkdtempSync(join(tmpdir(), 'autoshkola-browser-'));
const artifacts = resolve('verification-output');
mkdirSync(artifacts, { recursive: true });
Object.assign(process.env, { DATABASE_PATH: join(folder, 'browser.sqlite'), PORT: '0', HOST: '127.0.0.1', COOKIE_SECURE: 'false' });
delete process.env.ORIGIN;
let browser;
let server;
let database;
try {
  execFileSync(process.execPath, ['--disable-warning=ExperimentalWarning', 'src/seed.ts'], { stdio: 'inherit' });
  ({ server } = await import('../build/server.js'));
  ({ database } = await import('../build/db.js'));
  if (!server.listening) await once(server, 'listening');
  const root = 'http://127.0.0.1:' + server.address().port;
  browser = await chromium.launch({ executablePath: chrome, headless: true, chromiumSandbox: true });
  const context = await browser.newContext({ locale: 'ru-RU', viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  await context.addInitScript(() => {
    window.printInvocations = 0;
    window.print = () => { window.printInvocations++; };
  });
  const page = await context.newPage();
  page.setDefaultTimeout(7000);
  const browserErrors = [];
  page.on('pageerror', error => browserErrors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') browserErrors.push(msg.text()); });

  const name = 'Проверкин Максим Ильич';
  const topic = 'Практика в городе — контрольный сценарий';
  const groupName = 'Контрольная группа';
  const inquiry = 'Прошу уточнить время практики.\nВторая строка обращения.';
  const btn = name => page.getByRole('button', { name, exact: true });
  const heading = name => page.getByRole('heading', { name, exact: true });
  const text = value => page.getByText(value, { exact: true });
  const link = name => page.getByRole('link', { name, exact: true });
  const field = key => page.locator('#editor-form [name="' + key + '"]');
  const select = (key, label) => field(key).selectOption({ label });
  const wait = target => target.waitFor({ state: 'visible' });
  const clickNav = async (name, title = name) => {
    const menu = btn('Открыть меню');
    const item = page.getByRole('navigation', { name: 'Разделы' }).getByRole('link', { name, exact: true });
    if (await menu.isVisible() && await menu.getAttribute('aria-expanded') === 'false') await menu.click();
    await item.click();
    await wait(heading(title));
  };
  const layout = async width => {
    const sizes = await page.evaluate(() => ({ width: innerWidth, doc: document.documentElement.scrollWidth, body: document.body.scrollWidth }));
    assert.equal(sizes.width, width);
    assert.ok(sizes.doc <= width && sizes.body <= width, 'Горизонтальное переполнение: ' + JSON.stringify(sizes));
  };
  const login = async (user, password) => {
    await page.getByPlaceholder('Введите логин').fill(user);
    await page.getByPlaceholder('Введите пароль').fill(password);
    await btn('Войти').click();
    await wait(heading('Обзор'));
  };
  const logout = async () => {
    const menu = btn('Открыть меню');
    if (await menu.isVisible() && await menu.getAttribute('aria-expanded') === 'false') await menu.click();
    await btn('Выйти').click();
    await wait(heading('Вход в систему'));
  };

  await page.goto(root + '/login');
  await wait(heading('Вход в систему'));
  await page.screenshot({ path: join(artifacts, 'login-1440.png'), animations: 'disabled' });
  await login('admin', 'admin123');
  await layout(1440);
  await page.screenshot({ path: join(artifacts, 'dashboard-1440.png'), animations: 'disabled' });
  await btn('Включить светлую тему').click();
  await layout(1440);
  await page.screenshot({ path: join(artifacts, 'dashboard-light-1440.png'), animations: 'disabled' });
  await btn('Включить тёмную тему').click();
  await clickNav('Ученики');
  await page.screenshot({ path: join(artifacts, 'students-1440.png'), animations: 'disabled' });
  await clickNav('Обзор');
  await btn('Добавить ученика').click();
  await wait(heading('Новый ученик'));
  await field('name').fill(name);
  await field('phone').fill('+7 (900) 444-05-23');
  await field('birthDate').fill('1998-06-12');
  await btn('Сохранить').click();
  await wait(text('Ученик добавлен.'));
  await clickNav('Группы');
  await btn('Добавить группу').click();
  await field('name').fill(groupName);
  await select('instructorId', 'Иванов Сергей Андреевич');
  await select('studentId', name);
  await btn('Сохранить').click();
  await wait(link(groupName));
  await clickNav('Расписание');
  await layout(1440);
  await page.locator('button[data-action="new-lesson"][data-time="08:00"]').first().click();
  await wait(heading('Новое занятие'));
  await select('type', 'Индивидуальное');
  assert.equal(await field('groupId').isVisible(), false);
  await select('studentId', name);
  await select('instructorId', 'Иванов Сергей Андреевич');
  await field('topic').fill(topic);
  await btn('Сохранить').click();
  const appointment = page.getByRole('button', { name: /Практика в городе — контрольный сценарий/ });
  await appointment.click();
  await btn('Отметить проведённым').click();
  await appointment.waitFor({ state: 'hidden' });
  await clickNav('История занятий');
  await page.getByPlaceholder('Поиск по ученику, группе или дате').fill('Проверкин');
  await text('Основы ПДД').first().waitFor({ state: 'hidden' });
  await wait(page.locator('tbody').getByText(topic, { exact: true }));
  assert.equal(await page.locator('tbody tr').count(), 1);
  assert.match(await page.locator('tbody tr').innerText(), /Проведено/);
  console.log('✓ Браузер: администратор, ученик, группа, индивидуальное занятие и поиск по истории');

  await clickNav('Ученики');
  await page.getByPlaceholder('Поиск по ФИО или телефону').fill('Проверкин');
  await link('Петрова Анна Максимовна').waitFor({ state: 'hidden' });
  await link(name).click();
  await wait(heading(name));
  await wait(text(groupName));
  await btn('Принять оплату').first().click();
  await field('amount').fill('1850.25');
  await field('comment').fill('Тестовый взнос');
  await page.locator('#editor-form').getByRole('button', { name: 'Принять оплату' }).click();
  await wait(heading('Чек об оплате'));
  const receiptUrl = page.url();
  let receipt = await page.locator('.receipt').innerText();
  for (const value of [name, '000013', 'Обучение вождению', '1 850,25', 'Подпись']) assert.ok(receipt.includes(value));
  await btn('Печать').click();
  assert.equal(await page.evaluate(() => window.printInvocations), 1);
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.sidebar').isVisible(), false);
  assert.equal(await page.locator('.topbar').isVisible(), false);
  assert.equal(await btn('Печать').isVisible(), false);
  assert.equal(await page.locator('.receipt').isVisible(), true);
  await page.pdf({ path: join(artifacts, 'receipt-print.pdf'), format: 'A4', preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  console.log('✓ Браузер: оплата с копейками, печатный чек, вызов window.print и PDF');

  await logout();
  await login('instructor', 'instructor123');
  await clickNav('Группы');
  await wait(link('Вечерняя'));
  await wait(link(groupName));
  assert.equal(await link('Утренняя').count(), 0);
  await clickNav('Ученики');
  assert.equal(await link('Соколов Михаил Ильич').count(), 0);
  await link(name).click();
  await wait(heading(name));
  await btn('Изменить прогресс').click();
  await field('theoryProgress').fill('77');
  await btn('Сохранить').click();
  await wait(text('Прогресс обновлён.'));
  await wait(page.locator('.progress-detail > strong').filter({ hasText: '77%' }));
  await logout();
  await login('student', 'student123');
  await clickNav('Мой прогресс', 'Петрова Анна Максимовна');
  assert.equal(await btn('Изменить прогресс').count(), 0);
  await clickNav('Оплаты', 'Мои оплаты');
  assert.equal(await page.locator('tbody tr').count(), 1);
  await clickNav('Расписание');
  assert.equal(await btn('Новое занятие').count(), 0);
  assert.equal(await page.getByRole('button', { name: /Проверкин Максим Ильич/ }).count(), 0);
  await clickNav('Обращения');
  await btn('Новое обращение').click();
  await field('text').fill(inquiry);
  await btn('Отправить').click();
  const written = page.locator('.request-text').filter({ hasText: 'Вторая строка обращения.' });
  await wait(written);
  assert.equal(await written.textContent(), inquiry);
  await logout();
  await login('admin', 'admin123');
  await clickNav('Обращения');
  const row = page.locator('tbody tr').filter({ hasText: 'Прошу уточнить время практики.' });
  await row.getByRole('button', { name: 'Обработано', exact: true }).click();
  await wait(row.getByText('Обработано', { exact: true }));
  assert.equal(await row.getByRole('button', { name: 'Обработано', exact: true }).count(), 0);
  console.log('✓ Браузер: границы ролей, прогресс, создание и обработка многострочного обращения');

  await clickNav('Настройки');
  const [download] = await Promise.all([page.waitForEvent('download'), btn('Скачать JSON').click()]);
  const backup = join(folder, 'backup.json');
  await download.saveAs(backup);
  await page.locator('input[type="file"]').setInputFiles(backup);
  await btn('Импортировать').click();
  await wait(text('Создано 0, обновлено 0, ошибок 0.'));
  await clickNav('Ученики');
  await page.getByPlaceholder('Поиск по ФИО или телефону').fill('Проверкин');
  await link('Петрова Анна Максимовна').waitFor({ state: 'hidden' });
  await page.locator('tbody tr').filter({ hasText: name }).getByRole('button', { name: 'Удалить ученика' }).click();
  await wait(heading('Удалить ученика?'));
  await btn('Удалить').click();
  await link(name).waitFor({ state: 'hidden' });
  await btn('Отменить').click();
  await wait(link(name));
  console.log('✓ Браузер: скачивание и обратная загрузка JSON, удаление с подтверждением и отмена');

  await page.setViewportSize({ width: 360, height: 900 });
  await clickNav('Обзор');
  await layout(360);
  await page.locator('.toast').first().waitFor({ state: 'hidden' });
  await page.screenshot({ path: join(artifacts, 'dashboard-360.png'), fullPage: true, animations: 'disabled' });
  await clickNav('Ученики');
  await layout(360);
  const rowType = await page.locator('tbody tr').first().evaluate(node => getComputedStyle(node).display);
  assert.equal(rowType, 'grid');
  await btn('Добавить ученика').click();
  await wait(heading('Новый ученик'));
  await layout(360);
  await btn('Закрыть').click();
  await clickNav('Расписание');
  await layout(360);
  assert.equal(await page.locator('.day-header:visible').count(), 1);
  await page.locator('.mobile-days button').nth(2).click();
  await wait(page.locator('.mobile-days button:nth-child(3)[aria-pressed="true"]'));
  await page.goto(receiptUrl);
  await wait(heading('Чек об оплате'));
  await layout(360);
  await btn('Включить светлую тему').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.reload();
  await wait(heading('Чек об оплате'));
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await btn('Включить тёмную тему').click();
  assert.deepEqual(browserErrors, []);
  console.log('✓ Браузер: 1440 и 360 px, мобильные карточки и сетка, меню, тема, 0 ошибок консоли');
} finally {
  await browser?.close();
  if (server?.listening) await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  database?.close();
  rmSync(folder, { recursive: true, force: true });
}
